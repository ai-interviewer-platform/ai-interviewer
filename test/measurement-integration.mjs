import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
import { launchBrowser } from './browser/launch.mjs';
import { pageActivity as routes } from '../public/measurement-contract.js';
import { operatorToken, siteHarness } from './site-harness.mjs';

const policy = { version: 'fixture-v1', contactPurpose: 'Fixture invitation only.', operator: 'Fixture operator', contact: 'privacy@example.invalid', retention: 'Until the test ends.', processors: 'Isolated fixture.', emailProvider: 'none', confirmation: 'browser_receipt', deletion: 'Receipt withdrawal.' };
const env = { MEASUREMENT_COLLECTION_APPROVED: 'true', WAITLIST_COLLECTION_APPROVED: 'true', WAITLIST_POLICY: JSON.stringify(policy), PERSONAL_DATA_COLLECTION_APPROVED: 'false' };
const site = await siteHarness('measurement', env);
const { pool, base, request, operator } = site;
const event = (fields = {}) => ({ version: 'coursay-outcomes-v1', id: crypto.randomUUID(), name: 'landing_exposed', surface: 'landing', activity: 'none', action: 'none', authority: 'client', attribution: 'unknown', exposureId: crypto.randomUUID(), ...fields });
try {
  const start = new Date(Date.now() - 1000).toISOString();
  assert.equal((await (await request('/api/site-config', undefined, {}, { MEASUREMENT_COLLECTION_APPROVED: 'false' })).json()).measurementEnabled, false);
  assert.equal((await request('/api/measure', event(), {}, { MEASUREMENT_COLLECTION_APPROVED: 'false' })).status, 503);
  assert.equal((await (await request('/api/site-config', undefined, {}, { WAITLIST_OPERATOR_TOKEN: '' })).json()).measurementEnabled, false, 'No operator access means no collection');
  assert.equal((await (await request('/api/site-config')).json()).measurementEnabled, true);
  assert.equal((await request('/api/measure', event(), { origin: 'https://elsewhere.example' })).status, 403);
  assert.equal((await request('/api/measure', event({ name: 'email_typed' }))).status, 400);
  assert.equal((await request('/api/measure', event({ surface: 'review?attempt=private' }))).status, 400);
  assert.equal((await request('/api/measure', event({ name: 'landing_click', zone: 'hero', cellX: 40, cellY: 2, viewport: 'wide' }))).status, 400);
  assert.equal((await request('/api/measure', event({ attribution: 'newsletter' }))).status, 400, 'Attribution stays unknown');
  const lateLanding = crypto.randomUUID();
  await request('/api/measure', event({ name: 'practice_started', surface: 'sample', activity: 'sample', exposureId: lateLanding }));
  await request('/api/measure', event({ exposureId: lateLanding }));
  await request('/api/measure', event({ name: 'page_viewed', surface: 'terms', exposureId: crypto.randomUUID() }));
  const repeated = event({ email: 'leak@example.invalid', url: 'https://app.example/#personal?token=secret', text: 'free text' });
  assert.equal((await request('/api/measure', repeated)).status, 202);
  assert.equal((await request('/api/measure', repeated)).status, 202, 'A resent event is accepted once');
  const stored = await pool.query('SELECT * FROM measurement_events WHERE id = $1', [repeated.id]);
  assert.equal(stored.rows.length, 1);
  assert.equal(stored.rows[0].duplicate_count, 1);
  assert.doesNotMatch(JSON.stringify((await pool.query('SELECT * FROM measurement_events')).rows), /leak@example|token=secret|free text/);
  assert.equal((await request('/api/measure/report')).status, 401);
  assert.equal((await request('/api/measure/report', undefined, { authorization: `Bearer ${operatorToken}` })).status, 400, 'The operator chooses the window');
  await pool.query("INSERT INTO users (id, display_name, email) VALUES ('fixture-user', 'Fixture', 'fixture@example.invalid')");
  const attempt = (id, status, source = null) => pool.query(`INSERT INTO attempts (id, user_id, problem_id, mode, input_mode, status, setup_context, consent_at, disclosure_version, practice_goal, completed_at, source_attempt_id, source_checkpoint_id) VALUES ($1, 'fixture-user', 'sum-odd-positions-v1', 'coach', 'text', $2, '{}', now(), 'test', 'Practice', CASE WHEN $2 = 'completed' THEN now() END, $3::text, CASE WHEN $3::text IS NULL THEN NULL ELSE 'checkpoint' END)`, [id, status, source]);
  await attempt('first', 'active'); await attempt('open', 'active');
  await pool.query("INSERT INTO attempt_events (id, attempt_id, event_type, source_id, source_order, occurrence_offset_ms) VALUES ('event', 'first', 'code_submitted', 'event', 0, 0)");
  await pool.query("INSERT INTO code_checkpoints (id, attempt_id, event_id, source_code, checkpoint_type) VALUES ('checkpoint', 'first', 'event', '', 'submission')");
  await pool.query("UPDATE attempts SET status = 'completed', completed_at = now() WHERE id = 'first'");
  await attempt('retry', 'active', 'first');
  await pool.query("INSERT INTO reviews (id, attempt_id, status, completed_at, evidence_manifest) VALUES ('review', 'first', 'ready', now(), '{}')");
  console.log('PASS measurement gate, origin, allowlist, deduplication and private report access');

  const browser = await launchBrowser({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const sent = [];
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', item => { if (item.url().endsWith('/api/measure')) sent.push(JSON.parse(item.postData())); });
    const settle = () => page.waitForFunction(() => !document.querySelector('[aria-busy="true"]')).then(() => page.waitForTimeout(150));
    await page.goto(base);
    await page.locator('#waitlist-form').waitFor({ state: 'visible' });
    await page.locator('#landing-title').click();
    await page.locator('#waitlist-email').click();
    await page.locator('#waitlist-email').fill('private-person@example.invalid');
    await page.getByRole('link', { name: 'Explore the guided sample' }).focus();
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Run sample tests', exact: true }).click();
    await page.getByRole('button', { name: 'Review this moment', exact: true }).click();
    await page.getByRole('button', { name: 'Retry from here', exact: true }).click();
    await page.goto(`${base}/#interview`);
    await page.locator('#message').fill('MY PRIVATE TRANSCRIPT');
    await page.locator('#message').press('Enter');
    await settle();
    const names = sent.map(item => `${item.name}:${item.activity}:${item.action}`);
    for (const expected of ['landing_exposed:none:none', 'cta_selected:none:sample', 'landing_click:none:none', 'practice_started:sample:none', 'practice_completed:sample:none', 'review_opened:sample:none', 'retry_started:sample:none']) assert.ok(names.includes(expected), `${expected} in ${names}`);
    assert.equal(new Set(sent.map(item => item.exposureId)).size, 1, 'One document exposure links the journey');
    const clicks = sent.filter(item => item.name === 'landing_click');
    assert.deepEqual(clicks.map(item => item.zone), ['hero', 'hero'], 'Title and sample link clicks are kept; clicks in text fields are masked');
    assert.ok(clicks.every(item => item.cellX + item.cellY > 0), 'A keyboard activation counts at the control, not the page corner');
    for (const route of Object.keys(routes)) {
      await page.goto(`${base}/#${route}?token=secret-value&email=someone%40example.invalid`);
      await page.locator('h1, #personal-app').first().waitFor();
      await settle();
      assert.ok(sent.some(item => item.name === 'page_viewed' && item.surface === route && item.activity === routes[route]), `page_viewed covers #${route}`);
    }
    const payloads = JSON.stringify(sent);
    for (const secret of ['private-person', 'example.invalid', 'PRIVATE TRANSCRIPT', 'secret-value', 'token=', '127.0.0.1', 'def ', 'return ']) assert.ok(!payloads.includes(secret), `Measurement payloads exclude ${secret}`);
    assert.deepEqual([...new Set(sent.flatMap(Object.keys))].sort(), ['action', 'activity', 'attribution', 'authority', 'cellX', 'cellY', 'exposureId', 'id', 'name', 'surface', 'version', 'viewport', 'zone'].sort());
    assert.deepEqual(errors, []);
    console.log('PASS browser journey events, sitewide page coverage, masked clicks and payload exclusions');

    const outage = await context.newPage();
    await outage.route('**/api/measure', route => route.fulfill({ status: 503, body: '{}' }));
    await outage.route('**/api/site-config', route => route.abort());
    await outage.goto(base);
    await outage.locator('#waitlist-email').fill('outage@example.invalid');
    await outage.locator('#waitlist-consent').check();
    await outage.locator('#waitlist-form button').click();
    await outage.locator('#waitlist-success').waitFor({ state: 'visible' });
    await outage.goto(`${base}/#sample`);
    await outage.getByRole('button', { name: 'Run sample tests', exact: true }).click();
    await outage.getByText(/Simulated result/).first().waitFor();
    await outage.close();
    const quiet = await browser.newContext();
    await quiet.addInitScript(() => Object.defineProperty(Navigator.prototype, 'globalPrivacyControl', { get: () => true }));
    const privatePage = await quiet.newPage();
    let privateRequests = 0;
    privatePage.on('request', item => { if (item.url().endsWith('/api/measure')) privateRequests += 1; });
    await privatePage.goto(base);
    await privatePage.locator('#landing-title').click();
    await privatePage.waitForTimeout(300);
    assert.equal(privateRequests, 0, 'Global Privacy Control disables measurement');
    await quiet.close();
    console.log('PASS measurement and site-config outage keep the waitlist and sample working; Global Privacy Control sends nothing');

    const end = new Date(Date.now() + 1000).toISOString();
    const report = await operator(`/api/measure/report?start=${encodeURIComponent(start)}&end=${encodeURIComponent(end)}`);
    assert.deepEqual(report.window, { start, end, clock: 'server receipt time' });
    const documents = new Set(sent.filter(item => item.name === 'landing_exposed').map(item => item.exposureId)).size + 2;
    assert.equal(report.landing.documents, documents, 'Browser documents plus two API fixtures; blocked outage events are missing, not counted');
    assert.equal(report.landing.unattributedDocuments, 1, 'The legal page view without a landing exposure');
    assert.equal(report.landing.steps.find(step => step.name === 'practice_started').documents, 1, 'A start before the landing exposure is not a landing step');
    assert.deepEqual(report.landing.steps.find(step => step.name === 'cta_selected' && step.action === 'sample'), { name: 'cta_selected', activity: 'none', action: 'sample', documents: 1 });
    assert.deepEqual(report.landing.steps.find(step => step.name === 'retry_started'), { name: 'retry_started', activity: 'sample', action: 'none', documents: 1 });
    assert.equal(report.events.find(row => row.name === 'landing_exposed').duplicates, 1);
    assert.deepEqual(report.personalCohort, { started: 2, completed: 1, openAtEnd: 1, reviewsReady: 1, reviewedRetried: 1 });
    assert.deepEqual(report.waitlist, { joined: 1, withdrawn: 0 });
    assert.deepEqual([...new Set(report.heatmap.map(cell => `${cell.viewport}:${cell.zone}`))], ['wide:hero']);
    assert.equal(report.heatmap.reduce((total, cell) => total + cell.clicks, 0), 2);
    assert.ok(report.limitations.some(line => /not.*conversion/i.test(line)));
    assert.equal((await operator(`/api/measure/report?start=${encodeURIComponent(end)}&end=${encodeURIComponent(start)}`)).error, 'Choose a start before the end.');

    const inspect = await context.newPage();
    await inspect.goto(`${base}/#operator`);
    await inspect.getByLabel('Operator token').fill(operatorToken);
    await inspect.getByLabel('Window start').fill(start.slice(0, 16));
    await inspect.getByLabel('Window end').fill(new Date(Date.now() + 60_000).toISOString().slice(0, 16));
    await inspect.getByRole('button', { name: 'Load report' }).click();
    await inspect.getByRole('heading', { name: 'Landing heatmap' }).waitFor();
    assert.match(await inspect.locator('#operator-report').innerText(), new RegExp(`${documents} landing documents`));
    assert.equal(await inspect.locator('.heat-cell[data-clicks]').evaluateAll(cells => cells.reduce((total, cell) => total + Number(cell.dataset.clicks), 0)), 2);
    assert.deepEqual((await new AxeBuilder({ page: inspect }).include('#main').analyze()).violations.map(item => item.id), []);
    console.log('PASS operator report: document funnel, server cohort, duplicates, heatmap and stated limitations');
  } finally { await browser.close(); }
} finally { await site.close(); }
