import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
import { feedbackQuestions, pageFeature } from '../public/feedback-questions.js';
import { pageActivity } from '../public/measurement-contract.js';
import { launchBrowser } from './browser/launch.mjs';
import { operatorToken, siteHarness } from './site-harness.mjs';

const site = await siteHarness('feedback', { FEEDBACK_COLLECTION_APPROVED: 'true', MEASUREMENT_COLLECTION_APPROVED: 'true', PERSONAL_DATA_COLLECTION_APPROVED: 'false' });
const { pool, base, request, operator } = site;
const answer = (fields = {}) => ({ questionId: 'landing-clarity', questionVersion: 1, surface: 'landing', answer: 'partly', text: 'The sample link was hard to spot.', ...fields });
const records = async (query = '') => (await operator(`/api/feedback/records${query}`)).records;
try {
  assert.deepEqual(Object.keys(pageFeature).sort(), Object.keys(pageActivity).sort(), 'Every page has a feedback question');
  assert.equal((await (await request('/api/site-config', undefined, {}, { FEEDBACK_COLLECTION_APPROVED: 'false' })).json()).feedbackEnabled, false);
  assert.equal((await request('/api/feedback', answer(), {}, { FEEDBACK_COLLECTION_APPROVED: 'false' })).status, 503);
  assert.equal((await request('/api/feedback', answer(), { origin: 'https://elsewhere.example' })).status, 403);
  for (const invalid of [{ questionId: 'review-understanding' }, { questionVersion: 2 }, { answer: 'love-it' }, { answer: null, text: '   ' }, { surface: 'operator' }, { text: 'x'.repeat(2001) }]) assert.equal((await request('/api/feedback', answer(invalid))).status, 400, JSON.stringify(invalid).slice(0, 80));
  assert.equal((await request('/api/feedback', answer({ answer: null }))).status, 201, 'Free text alone is a response');
  assert.equal((await request('/api/feedback', answer({ text: '' }))).status, 201, 'A preset alone is a response');
  assert.equal((await request('/api/feedback', answer(), { cookie: 'better-auth.session_token=fixture' })).status, 201, 'A signed-in person submits the same way; the harness session resolver throws if the session is read');
  assert.equal((await request('/api/feedback', answer({ answer: null, text: '  Keep my spacing.  ' }))).status, 201);
  assert.equal((await request('/api/feedback/records')).status, 401);
  const saved = await records();
  assert.equal(saved.length, 4);
  assert.ok(saved.some(record => record.response_text === '  Keep my spacing.  '), 'Text is stored exactly as written');
  assert.deepEqual(Object.keys(saved[0]).sort(), ['activity', 'answer', 'category', 'created_at', 'feature', 'id', 'question_id', 'question_version', 'resolution', 'response_text', 'status', 'surface', 'updated_at']);
  assert.deepEqual({ feature: saved[0].feature, activity: saved[0].activity, status: saved[0].status }, { feature: 'landing', activity: 'none', status: 'new' });
  assert.equal((await request('/api/feedback/records', { id: saved[0].id, status: 'resolved' }, { authorization: `Bearer ${operatorToken}` })).status, 400, 'A resolution needs its record');
  const triaged = await operator('/api/feedback/records', { id: saved[0].id, category: 'usability', status: 'resolved', resolution: 'Made the sample link larger.' });
  assert.deepEqual({ category: triaged.record.category, status: triaged.record.status, resolution: triaged.record.resolution }, { category: 'usability', status: 'resolved', resolution: 'Made the sample link larger.' });
  assert.equal(triaged.record.response_text, saved[0].response_text, 'The original response is preserved');
  await assert.rejects(pool.query("UPDATE feedback_responses SET response_text = 'rewritten' WHERE id = $1", [saved[0].id]), /original feedback is immutable/);
  await assert.rejects(pool.query("UPDATE feedback_responses SET id = 'replaced' WHERE id = $1", [saved[0].id]), /original feedback is immutable/);
  assert.equal((await records('?status=resolved')).length, 1);
  assert.equal((await records('?feature=review')).length, 0);
  assert.equal((await records('?surface=landing&status=new')).length, 3);
  assert.equal((await request('/api/feedback/records?status=unknown', undefined, { authorization: `Bearer ${operatorToken}` })).status, 400);
  await operator('/api/feedback/records', { action: 'delete', id: saved[2].id });
  assert.equal((await records()).length, 3);
  await pool.query('DELETE FROM feedback_responses');
  console.log('PASS feedback gate, origin, question versions, answer semantics, private triage, filters, immutability and deletion');

  const browser = await launchBrowser({ headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/measure', route => route.abort());
    const toggle = page.getByRole('button', { name: 'Feedback', exact: true });
    await page.goto(base);
    await toggle.waitFor();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    await toggle.focus();
    await page.keyboard.press('Enter');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.getByRole('group', { name: feedbackQuestions.landing.question }).isVisible(), true);
    assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('type')), 'radio', 'Focus moves to the first answer');
    assert.equal(await page.locator('#feedback-panel input[type=radio]:checked').count(), 0, 'No preset is preselected');
    assert.deepEqual((await new AxeBuilder({ page }).include('#site-support').analyze()).violations.map(item => item.id), [], 'Open form');
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await toggle.evaluate(element => element === document.activeElement), true, 'Escape returns focus to the control');
    await toggle.click();
    await toggle.focus();
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false', 'Escape on the control closes the open panel');
    await toggle.click();
    await page.getByLabel('Partly clear').check();
    await toggle.click();
    await toggle.click();
    assert.equal(await page.getByLabel('Partly clear').isChecked(), true, 'Collapsing keeps the draft');
    await page.getByRole('button', { name: 'Cancel' }).focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#feedback-panel').isHidden(), true);
    assert.equal(await toggle.evaluate(element => element === document.activeElement), true, 'Cancel returns focus to the control');
    assert.equal(await pool.query('SELECT 1 FROM feedback_responses').then(result => result.rowCount), 0, 'Dismissal records nothing');
    await toggle.click();
    assert.equal(await page.locator('#feedback-panel input[type=radio]:checked').count(), 0, 'Cancel clears the draft');
    await page.getByRole('button', { name: 'Send feedback' }).click();
    assert.match(await page.locator('#feedback-error').innerText(), /Choose an answer or add a comment/);
    await page.getByLabel('Unclear').check();
    await page.getByLabel(/Anything to add/).fill('Explain the voice requirement sooner.');
    await page.route('**/api/feedback', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"Fixture outage."}' }));
    await page.getByRole('button', { name: 'Send feedback' }).click();
    await page.getByText(/Fixture outage/).waitFor();
    assert.equal(await page.getByLabel(/Anything to add/).inputValue(), 'Explain the voice requirement sooner.', 'A failed save keeps the draft');
    await page.unroute('**/api/feedback');
    await page.getByRole('button', { name: 'Send feedback' }).click();
    await page.getByText('Thank you. Your feedback was saved.').waitFor();
    const browserRecords = await records();
    assert.equal(browserRecords.length, 1, 'One save after one dismissal and one failure');
    assert.deepEqual([browserRecords[0].question_id, browserRecords[0].answer, browserRecords[0].response_text], ['landing-clarity', 'unclear', 'Explain the voice requirement sooner.']);
    assert.deepEqual((await new AxeBuilder({ page }).include('#site-support').analyze()).violations.map(item => item.id), []);
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');

    // Every page offers its own question and saves its page, feature and activity.
    await pool.query('DELETE FROM feedback_responses');
    for (const [route, feature] of Object.entries(pageFeature)) {
      await page.goto(`${base}/#${route}`);
      await page.locator('h1, #personal-app').first().waitFor();
      await toggle.click();
      await page.getByRole('group', { name: feedbackQuestions[feature].question }).locator('input').first().check();
      await page.getByRole('button', { name: 'Send feedback' }).click();
      await page.getByText('Thank you. Your feedback was saved.').waitFor();
      await page.keyboard.press('Escape');
    }
    const byPage = Object.fromEntries((await records()).map(record => [record.surface, [record.feature, record.activity, record.question_id]]));
    assert.deepEqual(byPage, Object.fromEntries(Object.entries(pageFeature).map(([route, feature]) => [route, [feature, pageActivity[route], feedbackQuestions[feature].id]])));
    await pool.query('DELETE FROM feedback_responses');
    await page.goto(`${base}/#review?source=sample`);
    await page.getByRole('button', { name: 'Disagree with this feedback' }).waitFor();
    await toggle.click();
    assert.match(await page.locator('#feedback-panel').innerText(), /To dispute a review finding, use “Disagree with this feedback”/);
    await page.getByLabel('Hard to follow').check();
    await page.getByRole('button', { name: 'Send feedback' }).click();
    await page.getByText('Thank you. Your feedback was saved.').waitFor();
    assert.equal(await page.getByText('Finding disputed').count(), 0, 'General feedback leaves the correction flow untouched');
    await page.getByRole('button', { name: 'Disagree with this feedback' }).click();
    await page.getByRole('heading', { name: 'Disagree with this feedback' }).waitFor();
    await page.getByRole('button', { name: 'Close dialog' }).click();
    const [sampleReview] = await records('?feature=review');
    assert.deepEqual({ surface: sampleReview.surface, activity: sampleReview.activity, question: sampleReview.question_id }, { surface: 'review', activity: 'sample', question: 'review-understanding' });

    const broken = await context.newPage();
    await broken.route('**/app.js', route => route.abort());
    await broken.route('**/api/site-config', route => route.abort());
    await broken.goto(`${base}/#sample`);
    await broken.getByRole('button', { name: 'Feedback', exact: true }).click();
    await broken.getByLabel('Somewhat confusing').check();
    await broken.getByRole('button', { name: 'Send feedback' }).click();
    await broken.getByText('Thank you. Your feedback was saved.').waitFor();
    await broken.close();
    assert.deepEqual((await records('?surface=sample')).map(record => [record.activity, record.answer]), [['sample', 'confusing']]);
    assert.deepEqual(errors, []);
    console.log('PASS feedback control keyboard and focus, dismissal, errors, sitewide questions, correction coexistence and independence from app and analytics failures');

    const inspect = await context.newPage();
    await inspect.goto(`${base}/#operator`);
    await inspect.getByLabel('Operator token').fill(operatorToken);
    await inspect.getByLabel('Feedback status').selectOption('new');
    await inspect.getByLabel('Feedback page').selectOption('sample');
    await inspect.getByRole('button', { name: 'Load feedback' }).click();
    const row = inspect.locator('.triage-record', { hasText: 'Somewhat confusing' });
    await row.getByLabel('Category').selectOption('content');
    await row.getByLabel('Status').selectOption('planned');
    await row.getByLabel('Resolution').fill('Move the voice note above the fold.');
    await row.getByRole('button', { name: 'Save triage' }).click();
    await row.getByText('Saved.').waitFor();
    const [planned] = await records('?status=planned');
    assert.deepEqual({ category: planned.category, resolution: planned.resolution, answer: planned.answer, surface: planned.surface }, { category: 'content', resolution: 'Move the voice note above the fold.', answer: 'confusing', surface: 'sample' });
    assert.deepEqual((await new AxeBuilder({ page: inspect }).include('#main').analyze()).violations.map(item => item.id), []);
    console.log('PASS browser submission → private operator triage with category, status and resolution');
  } finally { await browser.close(); }
} finally { await site.close(); }
